function variant(row: Row, suffix: string, brand: string | null, kcalDelta: number): ProductInput {
  const [name, category, baseBrand, servingSize, calories, protein, carbs, fat, sugar, fiber, salt, tags] = row;
  return {
    name: `${name}${suffix}`,
    description: `Хранителен продукт от категория ${category}, подходящ за проследяване на калории и макроси.`,
    category,
    brand: brand ?? baseBrand,
    servingSize,
    servingUnit: servingSize >= 250 && category === "drinks" ? "ml" : "g",
    calories: Math.max(0, calories + kcalDelta),
    protein,
    carbs,
    fat,
    sugar,
    fiber,
    salt,
    barcode: null,
    imageUrl: null,
    tags,
  };
}

function buildProducts(): ProductInput[] {
  return baseRows.flatMap((row, index) => [
    variant(row, "", null, 0),
    variant(row, " - био/премиум", index % 2 === 0 ? "FitLife Select" : null, index % 3 === 0 ? 8 : -4),
  ]);
}

async function main() {
  const repo = await import("../lib/server/repositories/products");
  let created = 0;
  let skipped = 0;

  for (const product of buildProducts()) {
    const existing = await repo.findByName(product.name);
    if (existing) {
      skipped += 1;
      continue;
    }
    await repo.create(product);
    created += 1;
  }

  console.log(`Food products seed complete. Created: ${created}. Skipped: ${skipped}.`);
}

main().catch((err) => {
  console.error("Food products seed failed:", err);
  process.exit(1);
});
